const dictionaries: Record<UiLang, Record<Key, string>> = { ru, en, uk }

export function resolveUiLang(setting: string, system: string): UiLang {
  const lang = (setting === 'system' ? system : setting).toLowerCase()
  if (lang.startsWith('uk')) return 'uk'
  if (['ru', 'be', 'kk', 'ky', 'tg', 'uz'].some(l => lang.startsWith(l))) return 'ru'
  return 'en'
}

export type Translate = (key: Key, vars?: Record<string, string | number>) => string

export function makeT(lang: UiLang): Translate {
  const dict = dictionaries[lang] || en
  return (key, vars) => {
    let text = dict[key] ?? en[key] ?? key
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v))
    return text
  }
}

export const I18n = createContext<{ t: Translate; lang: UiLang }>({ t: makeT('en'), lang: 'en' })

export const useI18n = () => useContext(I18n)
